#!/usr/bin/env python3
"""Compare ALL GNU-ton rider frames with the articulated candidate.

Both sources are generated by repository code: the current deployed rider uses
``gnu_ton_boss.scholar.render_frame``; the candidate uses ``RigDocument``.
This script does not call image generation, edit pixels by hand, or use the
rider's own presentation rig as a reference for modifying generated art.

Registration is FIXED by each source's rest frame. Every row/frame retains its
own animation translation: we never crop and re-center the moving character.

    cd tools/ambition_sprite2d_renderer
    python scripts/compare_gnu_ton_scholar_villain.py \
      --output-dir gnu_ton_scholar_review
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ambition_sprite2d_renderer.authoring.rigdoc import RigDocument  # noqa: E402
from ambition_sprite2d_renderer.targets.characters.gnu_ton_boss import (  # noqa: E402
    scholar,
    sprite_generator as shipped,
)

RIG = ROOT / (
    "ambition_sprite2d_renderer/targets/characters/rigged/"
    "gnu_ton_scholar_villain.rig.json"
)
BG = "#1b2332"
CARD = "#273147"
MUTED = "#a7b5c7"
TEXT = "#f3f0e7"
GOLD = "#edc26e"


def font(size: int, *, bold: bool = False):
    file = ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold
            else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    if Path(file).exists():
        return ImageFont.truetype(file, size)
    return ImageFont.load_default()


def all_frames(doc: RigDocument):
    """Render exactly the frames published for both registries, by row name."""
    rows = []
    built = {name: count for name, count, _duration in doc.rows()}
    for name, count, duration_seconds in scholar.ROWS:
        if built.get(name) != count:
            raise ValueError(f"Candidate row count differs from shipped: {name!r}")
        pairs = []
        for index in range(count):
            before = scholar.render_frame(
                shipped.Canvas, name, index, count,
                shipped.RIDER_FRAME, shipped.RIDER_PX_PER_UNIT,
                shipped.SUPERSAMPLE,
            )
            after = doc.render_frame(name, index, count)
            if before.getbbox() is None or after.getbbox() is None:
                raise ValueError(f"Empty comparison frame: {name} #{index}")
            pairs.append((before, after))
        rows.append((name, int(round(duration_seconds * 1000)), pairs))
    return rows


class Registration:
    """Same rest-height and fixed sole point, regardless of action pose."""

    def __init__(self, rest_pair: tuple[Image.Image, Image.Image]):
        self.orig_bbox = rest_pair[0].getbbox()
        self.rig_bbox = rest_pair[1].getbbox()
        self.height_before = self.orig_bbox[3] - self.orig_bbox[1]
        self.height_after = self.rig_bbox[3] - self.rig_bbox[1]
        self.orig_anchor = (rest_pair[0].width / 2, self.orig_bbox[3])
        self.rig_anchor = (rest_pair[1].width / 2, self.rig_bbox[3])

    def paste(self, canvas: Image.Image, sprite: Image.Image, *, revised: bool,
              rect: tuple[int, int, int, int], rest_height: float):
        x, y, w, h = rect
        old_height = self.height_after if revised else self.height_before
        anchor = self.rig_anchor if revised else self.orig_anchor
        factor = rest_height / old_height
        image = sprite.resize((round(sprite.width * factor),
                               round(sprite.height * factor)),
                              Image.Resampling.LANCZOS)
        origin = (round(x + w / 2 - anchor[0] * factor),
                  round(y + h - 9 - anchor[1] * factor))
        # Preserve per-frame positions, even when the character momentarily
        # crosses the stationary baseline. Directly alpha-composite the native
        # transparent sprite into the fixed frame-space registration.
        canvas.paste(image, origin, image)


def overview(rows, reg: Registration, path: Path):
    out = Image.new("RGB", (1370, 1770), BG)
    d = ImageDraw.Draw(out)
    d.text((30, 19), "GNU-TON SCHOLAR  |  SHIPPED vs RIGGED REDESIGN",
           font=font(27, bold=True), fill=TEXT)
    d.text((31, 64),
           "Matched animation frames, constant rest-height and foot anchor.",
           font=font(17), fill=MUTED)
    for j, (name, _ms, frames) in enumerate(rows):
        r, c = divmod(j, 2)
        bx, by = 22 + c * 670, 105 + r * 330
        d.rounded_rectangle((bx, by, bx + 657, by + 317),
                            radius=14, fill=CARD)
        d.text((bx + 16, by + 8), name.upper(),
               font=font(22, bold=True), fill=GOLD)
        i = round((len(frames) - 1) * .5)
        for k, (src, label) in enumerate(zip(frames[i], ("SHIPPED", "RIGGED"))):
            xx = bx + 18 + k * 317
            d.text((xx + 9, by + 40), label,
                   font=font(15, bold=True), fill=MUTED)
            d.line(((xx + 8, by + 289), (xx + 287, by + 289)),
                   fill="#536175", width=1)
            reg.paste(out, src, revised=bool(k),
                      rect=(xx + 10, by + 63, 283, 222),
                      rest_height=172)
            if k == 0:
                d.line(((xx + 306, by + 62), (xx + 306, by + 280)),
                       fill="#40516a", width=1)
        d.text((bx + 532, by + 13), f"{i+1}/{len(frames)}",
               font=font(13), fill=MUTED)
    out.save(path)


def full_contact_sheet(rows, reg: Registration, path: Path):
    cw, ch, hdrw, top = 246, 247, 110, 110
    out = Image.new("RGB", (hdrw + cw * 10, top + ch * len(rows) + 16), BG)
    d = ImageDraw.Draw(out)
    d.text((26, 22), "GNU-TON  |  ALL 82 MATCHED FRAMES",
           font=font(31, bold=True), fill=TEXT)
    d.text((26, 70),
           "In each cell: shipped left, new right. Registration is fixed from rest; animation offsets are preserved.",
           font=font(16), fill=MUTED)
    for ri, (name, _duration, frames) in enumerate(rows):
        y = top + ri * ch
        d.rectangle((0, y, hdrw, y + ch - 7), fill="#2c364d")
        d.text((7, y + 15), name.upper(),
               font=font(16, bold=True), fill=GOLD)
        d.text((8, y + 42), f"{len(frames)} frames",
               font=font(12), fill=MUTED)
        for index, (before, after) in enumerate(frames):
            x = hdrw + index * cw
            d.rounded_rectangle((x + 2, y + 2, x + cw - 4, y + ch - 8),
                                radius=7, fill=CARD)
            d.text((x + 12, y + 8), f"{index+1:02d}",
                   font=font(13, bold=True), fill=TEXT)
            d.text((x + 48, y + 10), "SHIPPED    /    NEW",
                   font=font(11), fill=MUTED)
            for k, src in enumerate((before, after)):
                reg.paste(out, src, revised=bool(k),
                          rect=(x + 5 + k * 120, y + 33, 116, 200),
                          rest_height=133)
    out.save(path)


def gifs(rows, reg: Registration, folder: Path):
    folder.mkdir(parents=True, exist_ok=True)
    for name, duration, pairs in rows:
        frames = []
        for index, (before, after) in enumerate(pairs):
            image = Image.new("RGB", (640, 368), BG)
            d = ImageDraw.Draw(image)
            d.text((20, 13), f"GNU-TON / {name.upper()}   frame {index+1}/{len(pairs)}",
                   font=font(22, bold=True), fill=TEXT)
            for k, (spr, label) in enumerate(zip((before, after),
                                                ("CURRENT", "REVISED"))):
                x = 18 + k * 310
                d.rounded_rectangle((x, 55, x + 294, 360),
                                    radius=14, fill=CARD)
                d.text((x + 15, 63), label,
                       font=font(16, bold=True), fill=GOLD)
                d.line((x + 20, 336, x + 275, 336),fill="#536175")
                reg.paste(image, spr, revised=bool(k),
                          rect=(x + 12, 92, 270, 239), rest_height=184)
            frames.append(image.quantize(colors=128))
        frames[0].save(folder / f"gnu_ton_{name}_comparison.gif",
                       save_all=True, append_images=frames[1:],
                       loop=0, duration=duration, disposal=2, optimize=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path,
                        default=Path("gnu_ton_scholar_review"))
    parser.add_argument("--no-gifs", action="store_true")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    rows = all_frames(RigDocument.load(RIG))
    reg = Registration(rows[0][2][0])
    overview(rows, reg, args.output_dir / "gnu_ton_scholar_comparison.png")
    full_contact_sheet(rows, reg, args.output_dir / "gnu_ton_scholar_all_frames.png")
    if not args.no_gifs:
        gifs(rows, reg, args.output_dir / "animation_comparisons")
    print(f"Compared {sum(len(frames) for _,_,frames in rows)} matched frames ")
    print(args.output_dir)


if __name__ == "__main__":
    main()
