_RADIUS = max(hypot(x, y) for x, y in _OUTLINE)


def mark_points(center: tuple[float, float], radius: float) -> list[tuple[float, float]]:
    """Fit the outline inside the given radius."""
    cx, cy = center
    scale = radius / _RADIUS
    return [(cx + x * scale, cy + y * scale) for x, y in _OUTLINE]
