"""A spec as the files the posing pipeline reads: a multiview SVG and rigs.

``character_svg`` writes one SVG with the five views side by side, each in its
own cell (Jon's 2026-10-21 grid ruling: a view is never stacked on another).
Each view is a layer in the contract of ``humanoid_svg_rig`` (the one Oiler
uses): part groups with ``data-rig-part`` / ``-bone`` / ``-z``, the blink and
talk overlays as opacity channels, and a layer of joint markers.

``build_rigs`` binds every view to the common humanoid skeleton with
``build_humanoid_view_document`` and seeds ``idle``, ``walk`` and ``talk``
clips for it; ``RigDocument`` renders the posed frames, and
``publish_sheet`` makes the sprite sheet with ``build_sheet``, like any
hand-made SVG rig. Every view is drawn at one scale (``PX_PER_CM``), so a
tall character is a tall sprite.
"""

from __future__ import annotations

import json
import math
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence, Tuple

from ..authoring.humanoid_svg_rig import AuxiliaryBoneSpec, HumanoidViewSpec, PartBinding, humanoid_document_from_geometry
from .body import Figure, build
from .draw import draw_view, view_joints
from .drawkit import Part
from .geometry import VIEWS, View
from .spec import CharacterSpec, check
from .svgout import Canvas, element_xml

#: SVG user units per centimetre.
UNIT = 2.5
#: One view's cell on the canvas, in user units; the ground line in it.
CELL_W, CELL_H, GROUND = 320.0, 600.0, 580.0
#: Sprite frame pixels per centimetre: a 172 cm person is 107 px tall.
PX_PER_CM = 0.62
FRAME_W, FRAME_H, FRAME_CX, FRAME_GROUND = 192, 256, 96.0, 246.0
DESIGN_ID = "chargen-v1"


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s or "character"


def view_label(spec: CharacterSpec, view: View) -> str:
    return f"{spec.name} - {view.label}"


@dataclass
class DrawnView:
    view: View
    parts: List[Part]
    joints: Dict[str, Tuple[float, float]]
    cell_x: float


def draw_views(spec: CharacterSpec, views: Sequence[View] = VIEWS) -> Tuple[Figure, List[DrawnView]]:
    fig = build(check(spec))
    out = []
    for i, view in enumerate(views):
        cv = Canvas(UNIT, (i * CELL_W + CELL_W / 2.0, GROUND))
        out.append(DrawnView(view, draw_view(fig, view, cv), view_joints(fig, view), i * CELL_W))
    return fig, out


def _esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def character_svg(spec: CharacterSpec, views: Sequence[View] = VIEWS, *, joints: bool = True,
                  state: Optional[Mapping[str, float]] = None, features: Optional[Mapping[str, bool]] = None) -> str:
    """The multiview SVG of ``spec``: one cell per view, left to right."""
    _fig, drawn = draw_views(spec, views)
    w = CELL_W * len(drawn)
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"',
        f'     width="{w:g}mm" height="{CELL_H:g}mm" viewBox="0 0 {w:g} {CELL_H:g}" data-character-design="{DESIGN_ID}">',
        "  <!-- GENERATED by ambition_sprite2d_renderer.chargen from the spec below; regenerate rather than edit.",
        f"       {_esc(spec.name)} ({spec.base}, seed {spec.seed}); {len(drawn)} views, the ground at y={GROUND:g};",
        f"       {UNIT:g} units per cm. A left view is the mirror of its right twin. -->",
        f'  <metadata id="chargen-spec"><![CDATA[{json.dumps(spec.to_dict(), sort_keys=True, separators=(",", ":"))}]]></metadata>',
    ]
    cv_unit = UNIT
    for dv in drawn:
        key = dv.view.key
        out.append(f'  <g id="view-{key}" inkscape:groupmode="layer" inkscape:label="{_esc(view_label(spec, dv.view))}" '
                   f'data-view-key="{key}" data-rig-pixel-origin="{dv.cell_x:g} 0">')
        for part in dv.parts:
            extra = f' data-rig-feature="{part.feature}"' if part.feature else ""
            if part.opacity:
                extra += f' data-rig-opacity="{part.opacity}" data-rig-opacity-default="{part.opacity_default or 0}"'
            if not _shown(part, state, features):
                # Hidden in the editor (an alternate face, a wardrobe item)
                # until an author shows it; the rig still draws it on demand.
                extra += ' data-rig-editor-visibility="editor-only" style="display:none"'
            out.append(f'    <g id="{key}-{part.name}" inkscape:groupmode="layer" inkscape:label="{part.label}" '
                       f'data-rig-part="{part.name}" data-rig-bone="{part.bone}" data-rig-z="{part.z:g}"{extra}>')
            for n, el in enumerate(part.els):
                out.append("      " + element_xml(el, f"{key}-{part.name}-{n}"))
            out.append("    </g>")
        if joints:
            out.append(f'    <g id="{key}-joints" inkscape:groupmode="layer" inkscape:label="Joints" '
                       'data-rig-editor-visibility="editor-only" style="display:none">')
            ox = dv.cell_x + CELL_W / 2.0
            for name, (x, y) in dv.joints.items():
                out.append(f'      <circle id="{key}-joint-{name}" data-rig-joint="{name}" cx="{ox + x * cv_unit:.2f}" '
                           f'cy="{GROUND + y * cv_unit:.2f}" r="1.2" fill="#ff00ff"/>')
            out.append("    </g>")
        out.append("  </g>")
    out.append("</svg>")
    return "\n".join(out) + "\n"


def _shown(part: Part, state: Optional[Mapping[str, float]], features: Optional[Mapping[str, bool]]) -> bool:
    """Whether ``part`` shows in a picture with these channel values and
    features (the defaults: the neutral face, the worn outfit)."""
    if part.opacity:
        v = (state or {}).get(part.opacity, float(part.opacity_default or 0))
        if v < 0.5:
            return False
    if part.feature:
        return bool((features or {}).get(part.feature, "@" not in part.name))
    return True


def view_svg(spec: CharacterSpec, view: View, *, state: Optional[Mapping[str, float]] = None,
             features: Optional[Mapping[str, bool]] = None) -> str:
    """One view alone in a document of one cell (for previews)."""
    return character_svg(spec, [view], joints=False, state=state, features=features)


# ---- rigs -----------------------------------------------------------------------------------


def view_spec(spec: CharacterSpec, view: View, target_height: float) -> HumanoidViewSpec:
    return HumanoidViewSpec(
        view=view_label(spec, view),
        name=f"{slug(spec.name)}_{view.key}",
        auxiliary_bones=tuple(AuxiliaryBoneSpec(f"{d}_grip", f"{d}_arm_hand", f"{d}_grip") for d in ("near", "far")),
        frame_width=FRAME_W,
        frame_height=FRAME_H,
        center_x=FRAME_CX,
        ground_y=FRAME_GROUND,
        target_height=target_height,
        collision_scale=1.7,
        # A run's feet ride the hips (`motion.run_pose`), so its lowest stride
        # is put on the ground the body stands on; a walk's feet are planted
        # by their own targets.
        plant={"run": "row", "dash": "row"},
    )


def view_document(spec: CharacterSpec, fig: Figure, dv: "DrawnView", svg_path: Path, rig_dir: Path) -> dict:
    """The rig of one drawn view, built from the figure's KNOWN joints.

    Nothing is read back off the drawing: the bones, their lengths and every
    part's pivot come from the spec's 3D body projected through the view, in
    SVG units, and the scale is fixed (``PX_PER_CM``), so the skeleton is
    exact for any proportions."""
    view = dv.view
    # Joints in the view's own pixel grid (``pixel_origin`` is its cell).
    ox = CELL_W / 2.0
    joints = {name: (ox + x * UNIT, GROUND + y * UNIT) for name, (x, y) in dv.joints.items()}
    parts = [
        PartBinding(
            name=p.name, bone=p.bone, z=p.z, include=tuple(f"{view.key}-{p.name}-{n}" for n in range(len(p.els))),
            opacity_channel=p.opacity, source_order=i, opacity_default=None if p.opacity_default is None else float(p.opacity_default),
            feature=p.feature,
        )
        for i, p in enumerate(dv.parts)
    ]
    doc = humanoid_document_from_geometry(
        spec=view_spec(spec, view, 0.0),
        joints=joints,
        parts=parts,
        scale=PX_PER_CM / UNIT,
        art_bottom=GROUND,
        svg_path=Path(svg_path),
        rig_dir=Path(rig_dir),
        pixel_origin=(dv.cell_x, 0.0),
    )
    for chain in doc["ik_chains"]:
        # The hand follows its forearm unless a clip names its angle.
        chain["pitch_mode"] = "follow_lower"
    worn = {p.feature for p in dv.parts if p.feature and "@" not in p.name}
    doc["features"] = {p.feature: False for p in dv.parts if p.feature and p.feature not in worn}
    doc["chargen"] = {"view": view.key, "yaw": view.yaw, "px_per_cm": PX_PER_CM, "spec_seed": spec.seed, "base": spec.base}
    doc["continuity"] = _head_on_neck(fig, view, doc)
    return doc


def _outline(loft, view: View, px) -> List[List[float]]:
    """A loft's silhouette in this view (its left edge down, its right edge
    up), mapped by ``px``."""
    levels = [loft.top + (loft.bottom - loft.top) * i / 16.0 for i in range(17)]
    sides = []
    for y in levels:
        pts = [view.project(q) for _a, q in loft.ring(y, 72)]
        sides.append((min(pts), max(pts)))
    return [px(lo) for lo, _hi in sides] + [px(hi) for _lo, hi in reversed(sides)]


def _head_on_neck(fig: Figure, view: View, doc: dict) -> List[dict]:
    """The audit's head-on-neck checks (``pose_audit``'s ``continuity``), in
    this view's rest frame pixels: the lower corners of the neck the head
    carries (``neck_upper``) stay on the neck the body carries (or a turn of
    the head opens a gap), and the top of the neck the body carries stays
    under the neck the head carries (or a head that rises leaves a stub of
    neck below it: a floating head)."""
    from ..authoring.rigdoc import RigDocument
    from .draw import NECK_SLEEVE

    probe = RigDocument(dict(doc, clips={}))
    rest, _ = probe.solve("", 0.0, sampled_channels={})
    hx, hy = rest["head"].origin
    jx, jy = view.project(fig.joints["neck"])

    def px(p: Tuple[float, float]) -> List[float]:
        return [round(hx + (p[0] - jx) * PX_PER_CM, 4), round(hy + (p[1] - jy) * PX_PER_CM, 4)]

    nk = fig.neck

    def extremes(y: float) -> Tuple[Tuple[float, float], Tuple[float, float]]:
        pts = [view.project(q) for _a, q in nk.ring(y, 72)]
        return min(pts), max(pts)

    y_s = nk.top + (nk.bottom - nk.top) * NECK_SLEEVE
    lo, hi = extremes(y_s)
    mid = ((lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2)
    # A little in from the sides: a head that only turns keeps them on the
    # neck; one that comes off (a gap, a float) takes them off it.
    corners = [px((c[0] + (mid[0] - c[0]) * 0.2, c[1] + (mid[1] - c[1]) * 0.2)) for c in (lo, hi)]
    levels = [nk.top + (nk.bottom - nk.top) * i / 8.0 for i in range(9)]
    sides = [extremes(y) for y in levels]
    polygon = [px(lo) for lo, _hi in sides] + [px(hi) for _lo, hi in reversed(sides)]
    # A turn may bend the neck's outline where the two meet (a kink of up
    # to a quarter of the neck's half-width); it may not open it.
    half = math.dist(lo, hi) / 2 * PX_PER_CM
    tol = round(0.25 * half + 0.25, 3)
    upper = [extremes(nk.top + (y_s - nk.top) * i / 6.0) for i in range(7)]
    sleeve = [px(a) for a, _b in upper] + [px(b) for _a, b in reversed(upper)]
    tlo, thi = extremes(nk.top + (y_s - nk.top) * 0.1)
    tmid = ((tlo[0] + thi[0]) / 2, (tlo[1] + thi[1]) / 2)
    tops = [px((c[0] + (tmid[0] - c[0]) * 0.2, c[1] + (tmid[1] - c[1]) * 0.2)) for c in (tlo, thi)]
    return [
        {"name": "head_on_neck", "carried": {"bone": "head", "points": corners}, "within": {"bone": "torso", "polygon": polygon},
         "tolerance": tol},
        {"name": "neck_under_head", "carried": {"bone": "torso", "points": tops},
         "within": {"bone": "head", "polygons": [sleeve, _outline(fig.head, view, px)]}, "tolerance": tol},
    ]


def build_rigs(spec: CharacterSpec, svg_path: Path, rig_dir: Path, views: Sequence[View] = VIEWS, *, clips=None,
               grip: str = "blade") -> Dict[str, Path]:
    """One ``.rig.json`` per view, bound to ``svg_path``, with its clips
    (``clips(fig, view, doc) -> {name: clip}``; the motion library by
    default, its item clips posed for the grip class ``grip``)."""
    rig_dir = Path(rig_dir)
    rig_dir.mkdir(parents=True, exist_ok=True)
    fig, drawn = draw_views(spec, views)
    from .motion import publish_views

    if clips is None:
        from functools import partial

        from .motion import library_clips

        clips = partial(library_clips, grip=grip)
    views_of = publish_views(fig)
    out: Dict[str, Path] = {}
    for dv in drawn:
        doc = view_document(spec, fig, dv, svg_path, rig_dir)
        doc["clips"] = clips(fig, dv.view, doc)
        # Which view the sprite sheet draws each clip from.
        doc["chargen"]["publish_views"] = {name: views_of.get(name, "side") for name in doc["clips"]}
        doc["chargen"]["grip"] = grip
        path = rig_dir / f"{doc['name']}.rig.json"
        path.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf8")
        out[dv.view.key] = path
    return out


def find_rigs(directory: Path) -> Dict[str, Path]:
    """The chargen rigs in ``directory``, by view key (read from each
    document's ``chargen`` record, not its file name)."""
    out: Dict[str, Path] = {}
    for path in sorted(Path(directory).glob("*.rig.json")):
        view = json.loads(path.read_text(encoding="utf8")).get("chargen", {}).get("view")
        if view:
            out[view] = path
    return out


@dataclass
class CharacterFiles:
    spec_path: Path
    svg_path: Path
    rigs: Dict[str, Path]


def write_character(spec: CharacterSpec, out_dir: Path, *, rigs: bool = True, grip: str = "blade") -> CharacterFiles:
    """``<out>/<slug>.chargen.json``, ``<slug>.svg`` and, when ``rigs``, one
    ``<slug>_<view>.rig.json`` per view (item clips posed for ``grip``)."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = slug(spec.name)
    spec_path = spec.save(out_dir / f"{name}.chargen.json")
    svg_path = out_dir / f"{name}.svg"
    svg_path.write_text(character_svg(spec), encoding="utf8")
    rig_paths = build_rigs(spec, svg_path, out_dir, grip=grip) if rigs else {}
    return CharacterFiles(spec_path, svg_path, rig_paths)


